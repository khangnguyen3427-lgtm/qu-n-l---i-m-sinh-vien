import pandas as pd
import matplotlib.pyplot as plt

# 1. Tạo DataFrame 10 sinh viên
df = pd.DataFrame({
    'Ho_ten': ['Minh', 'Khang', 'Hiếu', 'Cường', 'Hà', 'Nguyên', 'Thảo', 'Thành', 'Phúc', 'Huỳnh'],
    'Chuyen_can': [8, 9, 7, 8, 9, 6, 8, 7, 9, 8],
    'Giua_ky': [7, 8, 6, 9, 8, 5, 7, 6, 8, 7],
    'Cuoi_ky': [7.5, 8.5, 7, 8.5, 9, 6, 8, 6.5, 8.5, 8] })
display(df)

# 2. Tính điểm tổng kết
df['Tong_ket'] = df['Chuyen_can']*0.2 + df['Giua_ky']*0.3 + df['Cuoi_ky']*0.5

# 3. Xếp loại sinh viên
df['Xep_loai'] = pd.cut(df['Tong_ket'], bins=[-1, 5, 7, 8.5, 10], labels=['Yếu', 'Trung bình', 'Khá', 'Giỏi'])

# 4. Thống kê
print("Điểm TB lớp:", df['Tong_ket'].mean())
print("Cao nhất:", df.loc[df['Tong_ket'].idxmax(), 'Ho_ten'])
print("Thấp nhất:", df.loc[df['Tong_ket'].idxmin(), 'Ho_ten'])
print("Số SV đạt (>=5):", (df['Tong_ket'] >= 5).sum())

# 5. Trực quan hóa
plt.barh(df['Ho_ten'], df['Tong_ket'], color='skyblue')
plt.xlabel('Điểm tổng kết')
plt.ylabel('Tên sinh viên')
plt.title('Biểu đồ điểm tổng kết của 10 sinh viên')
plt.show()